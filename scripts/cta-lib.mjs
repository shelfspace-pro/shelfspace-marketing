export function listPages(root) {
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      const st = statSync(p);
      if (st.isDirectory()) { if (!SKIP_DIRS.has(name)) walk(p); continue; }
      if (!name.endsWith(".html")) continue;
      const rel = relative(root, p).split(sep).join("/");
      if (SKIP_FILES.has(rel) || /^google[0-9a-f]+\.html$/.test(rel)) continue;
      out.push(rel);
    }
  };
  walk(root);
  return out.sort();
}

export function pageId(rel) {
  let id = rel.replace(/\.html$/, "").replace(/(^|\/)index$/, "$1").replace(/\/$/, "");
  if (id === "") id = "home";
  return id.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

// cta ids must satisfy /contact's reader: /^[a-z0-9][a-z0-9_-]{0,79}$/i
export function ctaId(page, slot) {
  const room = 80 - slot.length - 1;
  const p = page.slice(0, room).replace(/-+$/, "");
  return `${p}-${slot}`;
}
