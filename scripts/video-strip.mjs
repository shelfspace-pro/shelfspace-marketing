// The homepage "Every video on the channel" strip (index.html #watch), built from the PUBLIC
// videos in video-catalog.json. build-tutorials.mjs rewrites it on every run; check-video-strip.mjs
// fails when index.html drifts from it.
//
// Why: the strip was pasted by hand and kept 29 store-side videos after the channel went
// brand-only (10/28/2026), plus thumbnails the browser had cached from before the 10/29 redesign.
//
// THUMB_V busts browser caches of i.ytimg.com thumbnails (YouTube ignores the query). Bump it
// whenever thumbnails are re-uploaded (scripts/training-videos/thumbnails/ in the platform repo).
export const THUMB_V = "20261029";
export const START = "<!-- VIDEO-STRIP:START (generated by scripts/video-strip.mjs, do not hand-edit) -->";
export const END = "<!-- VIDEO-STRIP:END -->";

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
export const thumb = (id, size = "mqdefault") => `https://i.ytimg.com/vi/${id}/${size}.jpg?v=${THUMB_V}`;

export const publicVideos = (catalog) =>
  catalog.videos.filter((v) => v.privacy === "public").sort((a, b) => String(b.uploadDate).localeCompare(String(a.uploadDate)));

function tile(v) {
  const len = v.durationLabel ? `<span class="vm-len">${esc(v.durationLabel)}</span>` : "";
  return `<a class="vm-tile" href="/tutorials/${esc(v.slug)}" tabindex="-1"><span class="vm-img"><img src="${thumb(v.videoId)}" alt="${esc(v.title)}" loading="lazy" width="320" height="180">${len}<span class="vm-pl" aria-hidden="true"><svg viewBox="0 0 24 24"><path d="M8 5v14l11-7z"/></svg></span></span><span class="vm-t">${esc(v.title)}</span></a>`;
}

/** One row. The track scrolls -50%, so each half repeats the set until it is wider than a wide screen. */
export function buildStrip(catalog) {
  const vids = publicVideos(catalog);
  const reps = Math.max(1, Math.ceil(8 / vids.length)); // ≥ 8 tiles (~2,000px) per half
  const half = Array.from({ length: reps }, () => vids.map(tile).join("")).join("");
  return `${START}
  <div class="vm reveal reveal-delay-2" aria-label="All ${vids.length} ShelfSpace videos">
    <div class="vm-label">Every video on the channel · ${vids.length} and counting</div>
      <div class="vm-row vm-row--a"><div class="vm-track">${half}${half}</div></div>
  </div>
  <div class="vf-foot reveal">
    <a href="/tutorials">Browse all ${vids.length} tutorials <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><line x1="5" y1="12" x2="19" y2="12"/><polyline points="12 5 19 12 12 19"/></svg></a>
  </div>
  ${END}`;
}

export function applyStrip(html, catalog) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error("video-strip: index.html has no VIDEO-STRIP markers");
  return html.slice(0, a) + buildStrip(catalog) + html.slice(b + END.length);
}
